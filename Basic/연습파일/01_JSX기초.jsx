// =====================================================
// 01. JSX 기초 연습
// =====================================================
// JSX = JavaScript + XML
// HTML처럼 생긴 자바스크립트 문법
// 브라우저가 이해할 수 있도록 내부적으로 JS로 변환됨

// ★ 기본 import (React 프로젝트 필수)
import React from 'react';

// =====================================================
// 1. 가장 기본적인 컴포넌트
// =====================================================
// 컴포넌트 = 함수 이름의 첫 글자는 반드시 대문자!
function Hello() {
    // return 안에 JSX를 작성
    return <h1>안녕하세요, React!</h1>;
}

// =====================================================
// 2. 변수를 JSX 안에서 사용하기 → { } 중괄호 사용
// =====================================================
function HelloName() {
    const name = '홍길동';         // 일반 자바스크립트 변수
    const age = 25;

    return (
        // JSX 여러 줄 작성 시 → 소괄호로 감싸기
        <div>
            <h1>이름: {name}</h1>       {/* 변수 출력 */}
            <p>나이: {age}세</p>
            <p>내년 나이: {age + 1}세</p>       {/* 표현식도 가능 */}
            <p>대문자 이름: {name.toUpperCase()}</p>  {/* 메서드 호출도 가능 */}
        </div>
    );
}

// =====================================================
// 3. JSX 규칙 정리
// =====================================================
function JSXRules() {
    const isLoggedIn = true;
    const items = ['사과', '바나나', '딸기'];

    return (
        <div>
            {/* 규칙1: 반드시 하나의 부모 태그로 감싸야 함 */}
            {/*        <div> 또는 <> (Fragment) 사용         */}

            {/* 규칙2: 태그는 반드시 닫아야 함 */}
            <br />          {/* 셀프 클로징 태그 */}
            <input />       {/* 이것도 셀프 클로징 */}

            {/* 규칙3: class → className 으로 작성 */}
            <p className="my-text">스타일 적용</p>

            {/* 규칙4: 조건부 표현 → 삼항연산자 사용 */}
            <p>{isLoggedIn ? '로그인됨' : '로그인 필요'}</p>

            {/* 규칙5: 배열 반복 → map() 사용 */}
            <ul>
                {items.map((item, index) => (
                    <li key={index}>{item}</li>   // key는 필수!
                ))}
            </ul>
        </div>
    );
}

// =====================================================
// 4. 최종 export (다른 파일에서 가져다 쓸 수 있게)
// =====================================================
// 하나만 export default 가능
export default JSXRules;

// 여러 개 export 할 때는 이렇게
export { Hello, HelloName };
